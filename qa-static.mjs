import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=fs.readFileSync('src/page.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {page}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert.equal((page.match(/<header\b/g)||[]).length,1,'Exactly one header');
assert.equal((page.match(/<section\b/g)||[]).length,6,'Six sections');
for(const id of ['home','about','mission','services','process','contact'])assert(page.includes(`id="${id}"`),id);
const ids=new Set([...page.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
for(const m of page.matchAll(/href="#([^"]+)"/g))assert(ids.has(m[1]),'Link target '+m[1]);
assert.equal((page.match(/<footer\b/g)||[]).length,1);
for(const field of ['name','email','message'])assert(page.includes(`name="${field}"`));
assert(page.includes('type="email"'));
assert(page.includes('role="status"'));
const css=fs.readFileSync('src/style.css','utf8');
for(const m of css.matchAll(/url\(['"]?\/assets\/([^'"\)]+)['"]?\)/g))assert(fs.existsSync('public/assets/'+m[1]),'Asset '+m[1]);
assert(css.includes('prefers-reduced-motion'));
assert(fs.existsSync('dist/index.html'));
const html=fs.readFileSync('dist/index.html','utf8');
for(const m of html.matchAll(/(?:src|href)="\.\/([^\"]+)"/g))assert(fs.existsSync('dist/'+m[1]),'Build resource '+m[1]);
console.log('PASS: six sections, one header, footer, internal links, contact fields, accessible status, artwork/font files, reduced-motion styling and build resources.');
